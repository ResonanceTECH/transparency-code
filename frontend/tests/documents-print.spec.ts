test('sample PDFs load under production CSP with an attachment-only same-origin frame exception', async ({ page }) => {
  const browserErrors: string[] = []
  page.on('console', (message) => { if (message.type() === 'error') browserErrors.push(message.text()) })
  await openPrototype(page)
  const application = await page.request.get('/prototype')
  const sample = await page.request.get(`/samples/${encodeURIComponent('Приказ_назначение.pdf')}`)
  expect(sample.status()).toBe(200)
  expect((await sample.body()).subarray(0, 5).toString()).toBe('%PDF-')
  const csp = application.headers()['content-security-policy']
  if (csp) {
    expect(csp).toContain("script-src 'self'")
    expect(csp).toContain("frame-src 'self' blob:")
    expect(csp).toContain("frame-ancestors 'none'")
    expect(application.headers()['x-frame-options']).toBe('DENY')
    expect(sample.headers()['x-frame-options']).toBe('SAMEORIGIN')
    expect(sample.headers()['content-security-policy']).toContain("frame-ancestors 'self'")
  }
  await nav(page, 'Документы')
  await page.getByRole('button', { name: 'Просмотреть Приказ_назначение.pdf', exact: true }).click()
  await expect(page.getByRole('dialog').locator('iframe')).toHaveAttribute('src', /^\/samples\//)
  await page.keyboard.press('Escape')
  expect(browserErrors).toEqual([])
})

