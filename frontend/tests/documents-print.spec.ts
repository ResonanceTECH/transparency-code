  const dialog = page.getByRole('dialog')
  await expect(dialog.locator('iframe')).toHaveAttribute('src', /^blob:/)
  await expect(page.getByRole('button', { name: 'Закрыть документ', exact: true })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: 'Закрыть', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Закрыть документ', exact: true })).toBeFocused()
  const firstDownload = page.waitForEvent('download')
  await dialog.getByRole('link', { name: 'Скачать', exact: true }).click()
  expect(await readFile((await (await firstDownload).path())!)).toEqual(firstFile.buffer)
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  await page.getByRole('button', { name: 'Сохранить и вернуться', exact: true }).click()
  await category(page, 'Надбавки и дополнительные выплаты')
